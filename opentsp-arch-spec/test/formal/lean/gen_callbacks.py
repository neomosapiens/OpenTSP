#!/usr/bin/env python3
"""Generate the Lean declarations of the model's 32 externally implemented functions (Lean is the proof assistant of the repository).

The Sail model declares functions whose implementation belongs to the harness: `val name = pure|impure {c: ...} : (args) -> ret`
(core/callbacks.sail, core/sram.sail, core/ecc.sail, slices/cu/cu_iq.sail). The Sail backends for Lean leave them undefined, so the
generated Lean cannot elaborate. This script reads those declarations from the model and writes `Env.lean`, the file given to
`sail --lean --lean-import-file`:

  * the file also defines `tdiv_int` and `tmod_int` (SHIMS below);
  * a `pure` callback is a trace sink (srf_write_callback, diag_callback, ...), defined as constant `()` in this register-state
    interpretation. Register-state theorems alone therefore do not establish external trace contents or ordering;
  * an `impure` callback reads or writes the harness's state (host and link FIFOs, the SRAM and instruction-queue storage): it is an
    `opaque` function into `SailM`. This declaration supplies no frame, storage, return-value or termination contract. A theorem
    inherits exactly the environment premises it states; those premises and production callback transfer need separate justification.

usage: gen_callbacks.py MODEL_DIR OUT_FILE      (prints the number of declarations; fails if it is not 32)
"""
import re
import sys
from pathlib import Path

FILES = ("core/callbacks.sail", "core/sram.sail", "core/ecc.sail", "slices/cu/cu_iq.sail")
EXPECTED = 32
DECL = re.compile(r"^val\s+(\w+)\s*=\s*(pure|impure)\s*\{[^}]*\}\s*:\s*(.*?)(?=^\S|\Z)", re.M | re.S)


def strip_comments(text):
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)


def split_top(text, sep=","):
    """Split on `sep` at bracket depth 0."""
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def lean_type(sail):
    sail = sail.strip()
    simple = {"nat": "Nat", "int": "Int", "bool": "Bool", "unit": "Unit", "string": "String"}
    if sail in simple:
        return simple[sail]
    found = re.fullmatch(r"range\(\s*(-?\d+)\s*,\s*(-?\d+)\s*\)", sail)
    if found:
        return "Nat" if int(found.group(1)) >= 0 else "Int"
    found = re.fullmatch(r"bits\(\s*(\d+)\s*\)", sail)
    if found:
        return "(BitVec %s)" % found.group(1)
    if re.fullmatch(r"\w+", sail):
        return sail                     # a type synonym of the model (vec, mem_slice, ecc_ov), defined in Out.Defs
    raise ValueError("no Lean type for the Sail type %r" % sail)


def declarations(model):
    found = {}
    for rel in FILES:
        text = strip_comments((Path(model) / rel).read_text())
        for match in DECL.finditer(text):
            name, kind, rest = match.group(1), match.group(2), " ".join(match.group(3).split())
            args, arrow, ret = rest.partition("->")
            args = args.strip()
            if not arrow:
                raise ValueError("%s: cannot read the signature of %s: %s" % (rel, name, rest))
            if args.startswith("(") and args.endswith(")"):
                args = args[1:-1]
            argtypes = [lean_type(a) for a in split_top(args)]
            found[name] = (kind, argtypes, lean_type(ret))
    return found


# The prelude's tdiv_int and tmod_int (truncating division and remainder) are extern names of prelude/prelude.sail; Sail's Lean
# library (lean-sail v6) does not define them under these names, so the generated modules that use them on naturals do not compile.
SHIMS = """/-- The prelude's `tdiv_int` and `tmod_int` (truncating division and remainder) over the integers and the naturals: the Sail library
    for Lean does not define them under these names. -/
class SailTrunc (α : Type) where
  tdiv : α → α → α
  tmod : α → α → α

instance : SailTrunc Int := ⟨Int.tdiv, Int.tmod⟩
instance : SailTrunc Nat := ⟨Nat.div, Nat.mod⟩

def tdiv_int {α : Type} [SailTrunc α] (a b : α) : α := SailTrunc.tdiv a b
def tmod_int {α : Type} [SailTrunc α] (a b : α) : α := SailTrunc.tmod a b
"""


def render(found):
    out = ["-- Generated by test/formal/lean/gen_callbacks.py from the declarations of the model's externally implemented functions.",
           "-- Do not edit: regenerate. `pure` callbacks are trace sinks (no effect on the model state); `impure` ones are opaque",
           "-- functions into SailM, with no implicit frame/storage/termination premise or C implementation refinement.",
           "import Sail",
           "import Out.Defs",
           "",
           "open Sail",
           "open Sail.ConcurrencyInterfaceV1",
           "",
           "namespace Out",
           "",
           SHIMS]
    for name in sorted(found):
        kind, args, ret = found[name]
        signature = " → ".join(args + ([ret] if kind == "pure" else ["SailM " + ret]))
        if kind == "pure":
            binders = " ".join("(_ : %s)" % a for a in args)
            out.append("def %s %s : %s := %s" % (name, binders, ret, "()" if ret == "Unit" else "default"))
            if ret != "Unit":
                raise ValueError("pure callback %s returns %s: a constant default would be an assumption" % (name, ret))
        else:
            out.append("opaque %s : %s" % (name, signature))
        out.append("")
    out.append("end Out")
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    found = declarations(argv[0])
    if len(found) != EXPECTED:
        print("gen_callbacks: found %d declarations, expected %d: %s" % (len(found), EXPECTED, sorted(found)), file=sys.stderr)
        return 1
    Path(argv[1]).write_text(render(found))
    print("gen_callbacks: %d declarations (%d pure, %d impure) -> %s" % (
        len(found), sum(1 for v in found.values() if v[0] == "pure"), sum(1 for v in found.values() if v[0] == "impure"), argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
