"""Compile the isa-db catalogue into C matchers for the exhaustive encoding check
(test/isa_db/exhaustive32.c, exhaustive64.c): catalogue_matchesN(w) returns how many
entries of width N accept w (fixed bits equal, every field value legal).

usage: gen_exhaustive_tables.py <encoding.json> <out.h> [config.json]
The default configuration is ref; the model and these tables must use the same configuration.
"""
import json, sys
from pathlib import Path
import re


def span(loc):
    a, _, b = loc.partition("-")
    return int(a), int(b or a)


def field_expr(v):
    parts, shift = [], 0
    for key in ("location", "hi_location", "top_location"):
        if key not in v:
            continue
        msb, lsb = span(v[key])
        size = msb - lsb + 1
        part = f"((w >> {lsb}) & 0x{(1 << size) - 1:x}ULL)"
        parts.append(f"({part} << {shift})" if shift else part)
        shift += size
    return "(" + " | ".join(parts) + ")", shift


def legal_expr(v, x, nbits, profile_vars, extensions):
    conds = []
    vals = v.get("values") or v.get("codes")
    if vals is not None:
        conds.append("(" + " || ".join(f"{x} == {c}ULL" for c in vals) + ")")
    for nv in v.get("not_values", []):
        conds.append(f"{x} != {nv}ULL")
    for extension, codes in v.get("extension_codes", {}).items():
        if extension not in extensions:
            conds += [f"{x} != {code}ULL" for code in codes]
    bound = None
    if "max_expr" in v:
        expression = re.fullmatch(r"([a-z_]+)(?:-([0-9]+))?", v["max_expr"])
        if expression is None or expression[1] not in profile_vars:
            raise ValueError("unsupported catalogue bound: " + v["max_expr"])
        bound = profile_vars[expression[1]] - int(expression[2] or 0)
    if v["kind"] == "simm16":
        lo, hi = v.get("min", -32768), v.get("max", 32767)
        if bound is not None:
            hi = min(hi, bound)
            lo = max(lo, -hi)
        conds.append(f"((int16_t){x} >= {lo} && (int16_t){x} <= {hi})")
    else:
        if "max" in v:
            conds.append(f"{x} <= {v['max']}ULL")
        if bound is not None:
            conds.append(f"{x} <= {bound}ULL")
        if "min" in v:
            conds.append(f"{x} >= {v['min']}ULL")
    if v["kind"] == "lane_count":
        conds.append(f"{x} < {profile_vars['vlanes']}ULL")
    if v["kind"] == "acc_index":
        conds.append(f"{x} < {profile_vars['acc_depth']}ULL")
    if "bool_values" in v:
        conds.append("(!btype || " + " || ".join(f"{x} == {c}ULL" for c in v["bool_values"]) + ")")
    return " && ".join(conds) if conds else "1"


def main():
    enc = json.load(open(sys.argv[1]))
    config_path = sys.argv[3] if len(sys.argv) > 3 else Path(__file__).resolve().parents[2] / "config/ref.json"
    cfg = json.load(open(config_path))
    profile_vars = {"vlanes": 16 * cfg["geometry"]["superlanes"],
                    "sram_words": 1 << cfg["sram"]["addr_bits"], "acc_depth": cfg["mxm"]["acc_depth"]}
    extensions = cfg.get("extensions", [])
    out = ["// Generated by gen_exhaustive_tables.py from isa-db/generated/encoding.json. Do not edit.",
           "#pragma once", "#include <stdint.h>"]
    for width in (32, 64):
        out.append(f"static int catalogue_matches{width}(uint64_t w) {{")
        out.append("  int n = 0;")
        for e in enc["instructions"]:
            if e["width"] != width:
                continue
            m = e["match"]
            mask = int("".join("0" if c == "-" else "1" for c in m), 2)
            val = int(m.replace("-", "0"), 2)
            body = [f"  /* {e['slice']} {e['name']} */",
                    f"  if ((w & 0x{mask:x}ULL) == 0x{val:x}ULL) {{"]
            btype = "0"
            conds = []
            for v in e["variables"]:
                x, nb = field_expr(v)
                if v["kind"] == "eltype_code":
                    btype = f"({x} >= 8 && {x} <= 10)"
                conds.append(legal_expr(v, x, nb, profile_vars, extensions))
            body.append(f"    int btype = {btype}; (void)btype;")
            body.append(f"    if ({' && '.join(conds) if conds else '1'}) n++;")
            body.append("  }")
            out += body
        out.append("  return n;")
        out.append("}")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
