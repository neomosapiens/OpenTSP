"""Exhaustive FP8 check, oracle side (, microarchitecture.md sec. 5 "FP8 element types").

The Sail unit test model/unit_tests/test_fp8.sail evaluates the model's lane kernels (k_binary, k_unary,
k_cmp, k_convert_any) on EVERY operand pair of both FP8 formats (256 x 256 for each binary operation and
comparison), on all 256 values of each unary operation and conversion, on all 2^16 binary16 values converted
to each format, and on 2^18 binary32 values converted to each format, and compares one digest per item. This
script computes the same digests from the independent oracle (test/oracle/numerics.py: exact Fractions, no
Sail), so the test fails if the model and the oracle differ on any single input.

The digest of a sequence r_0, r_1, ... of results is h = (h * 257 + r_i + 1) mod 1000000007, starting at 0.

usage: gen_fp8_digests.py [--check]       write model/unit_tests/test_fp8.sail (--check: compare, exit 1 on a difference)
"""
import os
import sys
from multiprocessing import Pool

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', 'oracle'))
import numerics as nx                      # noqa: E402

OUT = os.path.join(here, '..', '..', 'model', 'unit_tests', 'test_fp8.sail')
MOD = 1000000007
FMTS = ('e4m3', 'e5m2')
BIN = [('add', 0), ('sub', 3), ('mul', 6), ('max', 9), ('min', 10)]
CMP = ['eq', 'ne', 'lt', 'le', 'gt', 'ge']
UN = [('neg', 15), ('abs', 16), ('relu', 20)]
F32_LOWS = (0x0000, 0x8000, 0x8001, 0x7FFF)       # exact, the halfway point, just above and just below it


def fold(it):
    h = 0
    for r in it:
        h = (h * 257 + r + 1) % MOD
    return h


def item(spec):
    kind, t, arg = spec
    if kind == 'bin':
        return fold(nx.k_binary(arg, t, a, b) for a in range(256) for b in range(256))
    if kind == 'cmp':
        return fold(nx.k_cmp(arg, t, a, b) for a in range(256) for b in range(256))
    if kind == 'un':
        return fold(nx.k_unary(arg, t, a) for a in range(256))
    if kind == 'from16':
        return fold(nx.k_convert_any('f16', t, a) for a in range(65536))
    if kind == 'from32':
        return fold(nx.k_convert_any('f32', t, (a << 16) | lo) for a in range(65536) for lo in F32_LOWS)
    if kind == 'to':       # all 256 values of t converted to the type arg
        return fold(nx.k_convert_any(t, arg, a) for a in range(256))
    if kind == 'fromint':  # 256 raw values of the integer type arg (i16: a * 257, i32: a * 0x01010101) converted to t
        mul = {'i16': 257, 'i32': 16843009}.get(arg, 1)
        return fold(nx.k_convert_any(arg, t, a * mul) for a in range(256))
    raise ValueError(kind)


def specs():
    out = []
    for t in FMTS:
        out += [('bin', t, op) for _, op in BIN]
        out += [('cmp', t, m) for m in range(6)]
        out += [('un', t, op) for _, op in UN]
        out += [('from16', t, 0), ('from32', t, 0)]
        out += [('to', t, d) for d in ('f16', 'f32', 'i8', 'u8', 'i32', 'b8', 'e4m3' if t == 'e5m2' else 'e5m2')]
        out += [('fromint', t, s) for s in ('i8', 'u8', 'i16', 'i32', 'b8')]
    return out


SAIL_TYPE = {'e4m3': 'E4M3', 'e5m2': 'E5M2', 'f16': 'F16', 'f32': 'F32', 'i8': 'I8', 'u8': 'U8', 'i16': 'I16', 'i32': 'I32', 'b8': 'B8'}


def sail_call(spec):
    kind, t, arg = spec
    T = SAIL_TYPE[t]
    if kind == 'bin':
        return f'dg_bin(z, {arg}, {T})'
    if kind == 'cmp':
        return f'dg_cmp(z, {arg}, {T})'
    if kind == 'un':
        return f'dg_un(z, {arg}, {T})'
    if kind == 'from16':
        return f'dg_from16(z, {T})'
    if kind == 'from32':
        return f'dg_from32(z, {T})'
    if kind == 'to':
        return f'dg_to(z, {T}, {SAIL_TYPE[arg]})'
    return f'dg_fromint(z, {SAIL_TYPE[arg]}, {T})'


HEAD = '''// =====================================================================================
// SPDX-License-Identifier: Apache-2.0
// =====================================================================================

// Exhaustive tests of the FP8 element types e4m3 and e5m2 (microarchitecture.md sec. 5, "FP8 element
// types"). GENERATED by test/numerics/gen_fp8_digests.py from the independent oracle
// (test/oracle/numerics.py); do not edit. Each assertion compares the digest
// h = (h * 257 + r + 1) mod 1000000007 of the model kernel's results over a whole operand set with the
// oracle's: every pair of 8-bit values for the binary operations and comparisons, every 8-bit value
// for the unary operations and conversions, every binary16 value, and 2^16 binary32 patterns with four
// low halves (exact, halfway, just above, just below) for the conversions to the format. The leading argument z of
// the digest functions is always 0 and comes from a loop variable: with a literal argument sail --Oconstant-fold would
// evaluate the whole exhaustive loop while compiling the simulator (13 minutes instead of a few seconds).

function dg_step(h : int, r : bits(32)) -> int = tmod_int(h * 257 + unsigned(r) + 1, 1000000007)

function dg_bin(z : int, op : int, t : eltype) -> int = {
  var h : int = 0 * z;
  foreach (a from 0 to 255) {
    foreach (b from 0 to 255) { h = dg_step(h, k_binary(op, t, get_slice_int(32, a, 0), get_slice_int(32, b, 0))) }
  };
  h
}

function dg_cmp(z : int, mode : int, t : eltype) -> int = {
  var h : int = 0 * z;
  foreach (a from 0 to 255) {
    foreach (b from 0 to 255) { h = dg_step(h, k_cmp(mode, t, get_slice_int(32, a, 0), get_slice_int(32, b, 0))) }
  };
  h
}

function dg_un(z : int, op : int, t : eltype) -> int = {
  var h : int = 0 * z;
  foreach (a from 0 to 255) { h = dg_step(h, k_unary(op, t, get_slice_int(32, a, 0))) };
  h
}

function dg_from16(z : int, t : eltype) -> int = {
  var h : int = 0 * z;
  foreach (a from 0 to 65535) { h = dg_step(h, k_convert_any(F16, t, get_slice_int(32, a, 0))) };
  h
}

function dg_from32(z : int, t : eltype) -> int = {
  var h : int = 0 * z;
  foreach (a from 0 to 65535) {
    foreach (k from 0 to 3) {
      let lo : int = if k == 0 then 0 else if k == 1 then 32768 else if k == 2 then 32769 else 32767;
      h = dg_step(h, k_convert_any(F32, t, get_slice_int(32, a * 65536 + lo, 0)))
    }
  };
  h
}

function dg_to(z : int, src : eltype, dst : eltype) -> int = {
  var h : int = 0 * z;
  foreach (a from 0 to 255) { h = dg_step(h, k_convert_any(src, dst, get_slice_int(32, a, 0))) };
  h
}

function dg_fromint(z : int, src : eltype, dst : eltype) -> int = {
  var h : int = 0 * z;
  foreach (a from 0 to 255) {
    let iv : int = if src == I16 then a * 257 else if src == I32 then a * 16843009 else a;
    h = dg_step(h, k_convert_any(src, dst, get_slice_int(32, iv, 0)))
  };
  h
}
'''

LANDMARKS = '''
// Landmarks, by hand. e4m3: 1 sign, 4 exponent bits (bias 7), 3 fraction bits, no infinity, 0x7F and 0xFF are NaN,
// the largest finite value is 448 (0x7E), the smallest subnormal 2^-9 (0x01). e5m2: bias 15, 2 fraction bits,
// IEEE style: 0x7C is +infinity, 0x7D..0x7F NaN, the largest finite value is 57344 (0x7B), the smallest subnormal 2^-16.
$[test]
function test_fp8_landmarks() -> unit = {
  // decode
  assert(fdecode(FMT_E4M3, 0x0000007E).cls == FFinite & fdecode(FMT_E4M3, 0x0000007E).mag == 14 & fdecode(FMT_E4M3, 0x0000007E).e == 5);   // 448 = 14 * 2^5
  assert(fdecode(FMT_E4M3, 0x0000007F).cls == FNaN & fdecode(FMT_E4M3, 0x000000FF).cls == FNaN);
  assert(fdecode(FMT_E4M3, 0x00000001).mag == 1 & fdecode(FMT_E4M3, 0x00000001).e == -9);
  assert(fdecode(FMT_E5M2, 0x0000007C).cls == FInf & fdecode(FMT_E5M2, 0x000000FC).neg);
  assert(fdecode(FMT_E5M2, 0x0000007D).cls == FNaN & fdecode(FMT_E5M2, 0x0000007F).cls == FNaN);
  assert(fdecode(FMT_E5M2, 0x0000007B).mag == 7 & fdecode(FMT_E5M2, 0x0000007B).e == 13);   // 57344 = 7 * 2^13
  // conversions from binary32: nearest even, saturation (e4m3), infinity (e5m2), NaN
  assert(k_convert_any(F32, E4M3, 0x43E00000) == 0x0000007E);    // 448.0
  assert(k_convert_any(F32, E4M3, 0x43E80000) == 0x0000007E);    // 464.0 (the tie above 448) rounds to even and saturates
  assert(k_convert_any(F32, E4M3, 0x44800000) == 0x0000007E);    // 1024.0 saturates to 448
  assert(k_convert_any(F32, E4M3, 0xC4800000) == 0x000000FE);    // -1024.0 saturates to -448
  assert(k_convert_any(F32, E4M3, 0x7F800000) == 0x0000007E);    // +infinity saturates
  assert(k_convert_any(F32, E4M3, 0xFF800000) == 0x000000FE);
  assert(k_convert_any(F32, E4M3, 0x7FC00000) == 0x0000007F);    // NaN is the canonical NaN
  assert(k_convert_any(F32, E5M2, 0x47600000) == 0x0000007B);    // 57344.0, the largest finite value
  assert(k_convert_any(F32, E5M2, 0x47700000) == 0x0000007C);    // 61440.0, the tie above it, rounds to even: infinity
  assert(k_convert_any(F32, E5M2, 0x7F800000) == 0x0000007C);
  assert(k_convert_any(F32, E5M2, 0xFF800000) == 0x000000FC);
  assert(k_convert_any(F32, E5M2, 0x7FC00000) == 0x0000007E);
  assert(k_convert_any(F32, E4M3, 0x3F800000) == 0x00000038);    // 1.0 = 0 0111 000
  assert(k_convert_any(F32, E5M2, 0x3F800000) == 0x0000003C);    // 1.0 = 0 01111 00
  assert(k_convert_any(F32, E4M3, 0x3B000000) == 0x00000001);    // 2^-9, the smallest subnormal
  assert(k_convert_any(F32, E4M3, 0x3A800000) == 0x00000000);    // 2^-10, the tie to zero, rounds to even (zero)
  // operations
  assert(k_binary(0, E4M3, 0x0000007E, 0x0000007E) == 0x0000007E);   // 448 + 448 saturates
  assert(k_binary(6, E4M3, 0x0000007E, 0x0000007E) == 0x0000007E);   // 448 * 448 saturates
  assert(k_binary(6, E5M2, 0x0000007B, 0x0000007B) == 0x0000007C);   // 57344^2 overflows to infinity
  assert(k_binary(0, E5M2, 0x0000007C, 0x000000FC) == 0x0000007E);   // inf + -inf = canonical NaN
  assert(k_binary(0, E4M3, 0x0000007F, 0x00000038) == 0x0000007F);   // NaN propagates as the canonical NaN
  assert(k_unary(15, E4M3, 0x0000007F) == 0x0000007F);               // Neg of NaN is the canonical NaN
  assert(k_unary(15, E4M3, 0x00000038) == 0x000000B8);
  assert(k_unary(16, E5M2, 0x000000BC) == 0x0000003C);
  assert(k_unary(20, E5M2, 0x000000BC) == 0x00000000);
  assert(k_cmp(1, E4M3, 0x0000007F, 0x0000007F) == 0x000000FF);      // NaN != NaN
  assert(k_cmp(0, E4M3, 0x00000000, 0x00000080) == 0x000000FF);      // +0 == -0
  // the types are legal where the design says and illegal elsewhere
  assert(binop_legal(VADD, E4M3) & binop_legal(VMUL, E5M2) & binop_legal(VMAX, E4M3) & not(binop_legal(VAND, E4M3)) & not(binop_legal(VADD_SAT, E5M2)));
  assert(unop_legal(VNEG, E4M3) & unop_legal(VRELU, E5M2) & not(unop_legal(VNOT, E4M3)) & not(unop_legal(VTANH, E4M3)) & not(unop_legal(VEXP, E5M2)));
  assert(eltype_width(E4M3) == 1 & eltype_width(E5M2) == 1);
  assert(encdec_eltype(E4M3) == 0b01011 & encdec_eltype(E5M2) == 0b01100)
}
'''


def build():
    sp = specs()
    with Pool(min(8, os.cpu_count() or 1)) as pool:
        vals = pool.map(item, sp, chunksize=1)
    lines = [HEAD, LANDMARKS]
    lines.append('$[test]\nfunction test_fp8_exhaustive() -> unit = {')
    for s, v in zip(sp, vals):
        lines.append(f'  foreach (z from 0 to 0) {{ assert({sail_call(s)} == {v}, "{s[0]} {s[1]} {s[2]}") }};')
    lines[-1] = lines[-1].rstrip(';')
    lines.append('}\n')
    return '\n'.join(lines)


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        if open(OUT).read() != text:
            print('test_fp8.sail differs from the oracle digests; run gen_fp8_digests.py')
            sys.exit(1)
        print('test_fp8.sail matches the oracle digests (%d items)' % len(specs()))
    else:
        open(OUT, 'w').write(text)
        print('wrote', OUT, len(specs()), 'items')
