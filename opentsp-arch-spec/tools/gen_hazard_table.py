CLASS_WORDS = {"schedule", "data", "fault"}


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def classify(cell, raised):
    """The three-valued column (schedule, data, fault), or the older yes/no column (no = schedule unless fault state decides)."""
    words = cell.lower().replace("`", "").replace("*", "").split()
    word = words[0].strip(",.;:(") if words else ""
    if word in CLASS_WORDS:
        return word
    if word == "yes":
        return "data"
    if word == "no":
        return "fault" if ("injected fault" in raised or "fault state" in raised or "fault state" in cell) else "schedule"
    return "retired"


def table_codes(micro_text):
    """Rows of the section 8 diagnostic table: {code: (queue, class, retired)}; the class is read from the last column."""
    lines = micro_text.split("\n")
    start = None
    for i, line in enumerate(lines):
        if line.startswith("| Code | Raised when |"):
            start = i
            break
    if start is None:
        raise SystemExit("gen_hazard_table: the section 8 diagnostic table was not found in microarchitecture.md")
    out = {}
    for line in lines[start + 2:]:
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4:
            continue
        retired = cells[1].startswith("*Retired*")
        for code in (c.strip() for c in cells[0].split(",")):
            out[code] = (cells[2], classify(cells[-1], cells[1]), retired)
    return out


def enum_codes(sail_text):
    """The `diag_code` mapping: {enum member: code without the OTS-E- prefix}."""
    pat = r"^\s*([A-Z_]+)\s*<->\s*\"OTS-E-([A-Z]+-\d+)\""
    return {m.group(1): m.group(2) for m in re.finditer(pat, sail_text, re.M)}


def raise_sites(model_dir, members):
    """Files of the model that use each enum member outside diagnostics.sail."""
    uses = {m: [] for m in members}
    for base, _dirs, files in os.walk(model_dir):
        for name in sorted(files):
            if not name.endswith(".sail"):
                continue
            path = os.path.join(base, name)
            if os.path.abspath(path) == os.path.abspath(DIAGS):
                continue
            text = read(path)
            for m in members:
                if re.search(r"\b%s\b" % m, text):
                    uses[m].append(os.path.relpath(path, model_dir))
    return uses


# A hazard token at the start of a label, for example H-13.
STABLE = re.compile(r"H-\d+(?= |$)")
# An f-string literal of a test file: its text between the quotes, with `{...}` for each placeholder.
FSTRING = re.compile(r"""\bf(?:"([^"\n]*)"|'([^'\n]*)')""")


def pin_found(text, label):
    """Does the test file `text` carry the pinning label? Three ways, so that a generic rewrite of a test's label does not
    break a pin silently: the label as written; an f-string whose literal parts and placeholders give the label (the
    placeholder stands for any text); the stable token that starts the label (`H-13`) at the start of a string."""
    if label in text:
        return True
    for m in FSTRING.finditer(text):
        body = m.group(1) if m.group(1) is not None else m.group(2)
        if "{" not in body:
            continue
        parts = _split_placeholders(body)
        if sum(len(p) for p in parts[::2]) < 16:
            continue  # an f-string that is mostly placeholders would match any label
        pattern = "".join(".+?" if i % 2 else re.escape(part) for i, part in enumerate(parts))
        if re.fullmatch(pattern, label):
            return True
    token = STABLE.match(label)
    return bool(token) and re.search(r"""["']""" + re.escape(token.group(0)) + r"(?= |[\"'])", text) is not None


def _split_placeholders(body):
    """The parts of an f-string body around its `{...}` placeholders: literal, placeholder, literal, ... ('' where absent)."""
    parts, last = [], 0
    for m in re.finditer(r"\{[^{}]*\}", body):
        parts += [body[last:m.start()], m.group(0)]
        last = m.end()
    return parts + [body[last:]]


def problems(micro_text, sail_text, hazards=None, silent=None, model_dir=MODEL, tests_dir=TESTS, uses=None, texts=None):
    """Every disagreement between the sources and the hazard rows, as a list of strings. `texts` maps a test file name to
    its text in place of the file (the self-test)."""
    texts = texts or {}

    def test_text(fname):
        path = os.path.join(tests_dir, fname)
        if fname in texts:
            return texts[fname]
        return read(path) if os.path.exists(path) else None

    hazards = HAZARDS if hazards is None else hazards
    silent = SILENT if silent is None else silent
    errs = []
    table = table_codes(micro_text)
    enum = enum_codes(sail_text)
    live = {c for c, (_q, _cl, retired) in table.items() if not retired}
    for code in sorted(set(enum.values()) - set(table) - set(TABLE_PENDING)):
        errs.append("code %s is in diagnostics.sail but not in the section 8 table" % code)
    for code in sorted(set(TABLE_PENDING) & set(table)):
        errs.append("code %s now has a section 8 row: delete it from TABLE_PENDING" % code)
    for code in sorted(live - set(enum.values())):
        errs.append("code %s is in the section 8 table but has no member in diagnostics.sail" % code)
    if uses is None:
        uses = raise_sites(model_dir, list(enum))
    for member, files in sorted(uses.items()):
        if not files:
            errs.append("diagnostic %s (%s) is never raised in the model" % (member, enum[member]))
    covered = set()
    ids = set()
    for hid, _hazard, _formula, codes, klass, tests in hazards:
        if hid in ids:
            errs.append("duplicate hazard id %s" % hid)
        ids.add(hid)
        if klass not in CLASS_WORDS:
            errs.append("%s: class %r is not schedule, data or fault" % (hid, klass))
        for code in codes:
            if code not in table and code not in TABLE_PENDING:
                errs.append("%s names code %s, which is not in the section 8 table" % (hid, code))
                continue
            covered.add(code)
            col = table[code][1] if code in table else klass
            # a code of class `schedule` may have a data-dependent case (H-06 for OPR-001); the other pairs must agree
            if col in CLASS_WORDS and klass != col and not (col == "schedule" and klass == "data"):
                errs.append("%s: row class %s differs from the section 8 column (%s) of %s" % (hid, klass, col, code))
        if not tests:
            errs.append("%s has no pinning test" % hid)
        for fname, label in tests:
            text = test_text(fname)
            if text is None:
                errs.append("%s: test file %s does not exist" % (hid, fname))
            elif not pin_found(text, label):
                errs.append("%s: label %r does not occur in %s" % (hid, label, fname))
    for code in sorted(live - covered - RETIRED):
        errs.append("code %s of the section 8 table has no hazard row" % code)
    for hid, _c, _f, fname, label in silent:
        if hid in ids:
            errs.append("duplicate hazard id %s" % hid)
        ids.add(hid)
        text = test_text(fname)
        if text is None or not pin_found(text, label):
            errs.append("%s: label %r does not occur in %s" % (hid, label, fname))
    return errs


def render(hazards=None, silent=None):
    hazards = HAZARDS if hazards is None else hazards
    silent = SILENT if silent is None else silent
    lines = [BEGIN, "",
             "| No. | Hazard | Formula | Diagnostic | Found by `tsp-iss verify` | Pinning test |",
             "|---|---|---|---|---|---|"]
    found_by = {"schedule": "yes", "data": "no (data-dependent)", "fault": "no (fault-dependent)"}
    # A hazard whose rule reads the traffic of other chips or the host script is found only when the verifier is given them.
    found_note = {
        "H-16": "yes, on the manifest of the program (every chip, at both link latency bounds)",
        "H-17": "yes, on the manifest of the program (every chip, at both link latency bounds)",
        "H-18": "yes, on the manifest of the program and with the host script (`--host`) that sends the packets",
        "H-19": "yes, on the manifest of the program (a lone object with text on a link is refused)",
    }
    for hid, hazard, formula, codes, klass, tests in hazards:
        diag = ", ".join("OTS-E-" + c for c in codes)
        pins = "; ".join("`%s` \"%s\"" % (f, label) for f, label in tests)
        lines.append("| %s | %s | %s | %s | %s | %s |" % (hid, hazard, formula, diag, found_note.get(hid, found_by[klass]), pins))
    for hid, hazard, formula, fname, label in silent:
        lines.append("| %s | %s | %s | none | not applicable | `%s` \"%s\" |" % (hid, hazard, formula, fname, label))
    lines += ["", END]
    return "\n".join(lines)


def block_of(text):
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < 0 or b < a:
        return None
    return text[a:b + len(END)]


def main(argv):
    micro, sail = read(MICRO), read(DIAGS)
    if "--self-test" in argv:
        return self_test(micro, sail)
    errs = problems(micro, sail)
    if errs:
        print("gen_hazard_table: the sources disagree:", file=sys.stderr)
        for e in errs:
            print("  " + e, file=sys.stderr)
        return 1
    table = render()
    if "--write" in argv:
        text = read(ASSEMBLY)
        old = block_of(text)
        if old is None:
            print("gen_hazard_table: the markers are missing from assembly.md", file=sys.stderr)
            return 1
        with open(ASSEMBLY, "w", encoding="utf-8") as f:
            f.write(text.replace(old, table))
        return 0
    if "--check" in argv:
        if block_of(read(ASSEMBLY)) != table:
            print("gen_hazard_table: the hazard table of assembly.md is stale; run gen_hazard_table.py --write", file=sys.stderr)
            return 1
        # the self-test runs with every check, so the matching of the pins is itself checked in the gate that runs `--check`
        if self_test(micro, sail, quiet=True) != 0:
            print("gen_hazard_table: the self-test fails; run gen_hazard_table.py --self-test", file=sys.stderr)
            return 1
        print("gen_hazard_table: ok (%d hazards, %d unreported constraints)" % (len(HAZARDS), len(SILENT)))
        return 0
    print(table)
    return 0


def self_test(micro, sail, quiet=False):
    """Each mutation of an input must be reported; the unmutated inputs must be clean."""
    results = [("unmutated inputs are clean", problems(micro, sail) == [])]
    row = next(line for line in micro.split("\n") if line.startswith("| SXM-001 |"))
    results.append(("a code removed from the section 8 table", any("SXM-001" in e for e in problems(micro.replace(row, ""), sail))))
    mut = sail.replace('SXM_PERMUTE   <-> "OTS-E-SXM-001",', "")
    results.append(("a code removed from the enum mapping", any("SXM-001" in e for e in problems(micro, mut))))
    fewer = [h for h in HAZARDS if "RES-003" not in h[3]]
    results.append(("a code without a hazard row", any("RES-003" in e for e in problems(micro, sail, hazards=fewer))))
    bad = [h[:5] + ([("directed/directed.py", "no such label")],) if h[0] == "H-01" else h for h in HAZARDS]
    results.append(("a pinning test that does not exist", any("no such label" in e for e in problems(micro, sail, hazards=bad))))
    wrong = [h[:4] + ("fault",) + h[5:] if h[0] == "H-01" else h for h in HAZARDS]
    results.append(("a class that disagrees with the column", any("H-01" in e and "class" in e for e in problems(micro, sail, hazards=wrong))))
    unraised = {m: [] for m in enum_codes(sail)}
    results.append(("a diagnostic nobody raises", any("never raised" in e for e in problems(micro, sail, uses=unraised))))
    # a test that builds its label with an f-string, and one whose label was rewritten
    h13 = next(h for h in HAZARDS if h[0] == "H-13")
    fname = h13[5][0][0]
    numbered = h13[:5] + ([(fname, "20 LWs fill the buffer; the next is RES-002")],)
    fstring = {fname: 'check(f"{KLW} LWs fill the buffer; the next is RES-002", ok)\n'}
    results.append(("an f-string label whose placeholder stands for a number", not any("H-13" in e for e in problems(micro, sail, hazards=[numbered], texts=fstring))))
    rewritten = {fname: 'check(f"{KLW} LWs fill the buffer; the next is something else", ok)\n'}
    results.append(("an f-string label whose text changed", any("H-13" in e for e in problems(micro, sail, hazards=[numbered], texts=rewritten))))
    tokened = ("H-98", "a hazard", "f", ["TIM-001"], "schedule", [(fname, "H-98 20 LWs fill the buffer")])
    stable = {fname: 'check(f"H-98 {KLW} LWs fill, reworded", ok)\n'}
    results.append(("a label that starts with a stable token", not any("H-98" in e for e in problems(micro, sail, hazards=[tokened], texts=stable))))
    gone = {fname: 'check("nothing of the kind", ok)\n'}
    results.append(("a stable token that no test carries", any("H-98" in e for e in problems(micro, sail, hazards=[tokened], texts=gone))))
    ok = True
    for name, passed in results:
        if not quiet or not passed:
            print(("PASS " if passed else "FAIL ") + name)
        ok &= passed
    return 0 if ok else 1


