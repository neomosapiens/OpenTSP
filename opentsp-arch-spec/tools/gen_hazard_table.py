#!/usr/bin/env python3
"""Generate the hazard catalogue of `assembly.md` ("Scheduling constraints").

The catalogue is one numbered table: hazard, formula, diagnostic, checked without data, pinning test. It cannot drift from
the model because the generator reads the same sources as the rest of the specification and refuses to run when they
disagree:

  1. the diagnostic table of `microarchitecture.md` section 8 (codes, queue, data-dependent column);
  2. the `diag` enum and the `diag_code` mapping of `model/core/diagnostics.sail`, and the sites that raise each member
     (a use in another file of `model/`; a member nobody raises is an error);
  3. the hazard rows kept in this file (HAZARDS): the formula and the pinning test are written by hand, the rest is checked:
     every code of 1 and 2 appears in at least one row, every row names a code that exists, the class of the row (`schedule`,
     `data` or `fault`) agrees with the section 8 column, and every pinning test is a label that occurs in its test file.

Usage:
  gen_hazard_table.py              print the table
  gen_hazard_table.py --write      replace the block between the markers in assembly.md
  gen_hazard_table.py --check      exit 1 when assembly.md differs from the generated block, or a source disagrees
  gen_hazard_table.py --self-test  mutate the inputs in memory and confirm that each mutation is caught

The classes follow the three-valued column of the section 8 table: `schedule` codes depend on the text, the configuration and the timing only, so
`tsp-iss verify` (a run without data) finds them; `data` codes read data values; `fault` codes read the injected fault state.
"""
