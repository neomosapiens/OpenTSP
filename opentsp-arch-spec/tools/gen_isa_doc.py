def queue_map():
    """[(queue id, canonical name, unit)] and the alias names (assembly.md sec. 3,
    model/core/queues.sail)."""
    qs, aliases = [], {}
    for s in range(88):
        qs.append((s, f"MEM[{s}]", "MEM_W" if s < 44 else "MEM_E"))
        aliases[f"MEM.{'W' if s < 44 else 'E'}[{s % 44}]"] = s
    for a in range(16):
        qs.append((88 + a, f"VXM[{a}]", "VXM"))
    # The published split: per hemisphere 6 MXM queues (3 per plane) and 14 SXM-side
    # queues, the C2C TX and RX among them.
    for p in range(4):
        for k, sub in enumerate(["LW", "ABC", "ACC"]):   # LW, not W (W means west elsewhere)
            qs.append((104 + 3 * p + k, f"MXM[{p}].{sub}", "MXM_W" if p < 2 else "MXM_E"))
    for row, base in (("W", 116), ("E", 130)):
        k = 0
        for unit, sub, n in (("SXM", "DST", 4), ("SXM", "TSP", 2), ("SXM", "SHF", 2), ("SXM", "PRM", 1),
                             ("SXM", "SEL", 1), ("C2C", "TX", 2), ("C2C", "RX", 2)):
            for i in range(n):
                qs.append((base + k, f"{unit}.{row}.{sub}" + (f"[{i}]" if n > 1 else ""), f"{unit}_{row}_{sub}"))
                k += 1
    qs.append((CONTROL_QUEUE, "CU", "CU"))
    return qs, aliases


def diagnostics():
    """Every diagnostic code with the model's one-line meaning (model/core/diagnostics.sail)."""
    src = open(os.path.join(SPEC, "model", "core", "diagnostics.sail")).read()
    return {m.group(1): m.group(2).strip() for m in re.finditer(r"//\s*(OTS-E-[A-Z]+-\d+):\s*(.*)", src)}


def with_footprints(e):
    """The entry's encoding, with `streams` and `align` on each stream operand (FOOTPRINTS)."""
    enc = dict(e["encoding"])
    fp = FOOTPRINTS.get(e["name"], {})
    names = {v["name"] for v in enc["variables"] if v["kind"].startswith("stream")}
    if names != set(fp):
        raise SystemExit(f"gen_isa_doc.py: {e['name']}: stream operands {sorted(names)} != footprints {sorted(fp)}")
    enc["variables"] = [{**v, **fp[v["name"]]} if v["name"] in fp else v for v in enc["variables"]]
    return enc


