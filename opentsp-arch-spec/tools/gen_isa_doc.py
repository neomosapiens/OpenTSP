def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated outputs without changing them")
    args = parser.parse_args(argv[1:])
    es = entries()
    outs = {os.path.join(DOCS, "isa.md"): isa_md(es) + "\n", os.path.join(DOCS, "encoding.md"): encoding_md(es) + "\n",
            os.path.join(SPEC, "isa-db", "generated", "encoding.json"): encoding_json(es)}
    stale = []
    for p, text in outs.items():
        if args.check:
            if not os.path.exists(p) or open(p).read() != text:
                stale.append(p)
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w").write(text)
    if stale:
        print("out of date (run tools/gen_isa_doc.py):", *stale)
        return 1
    print(f"isa docs {'up to date' if args.check else 'written'}: {len(es)} encodings")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
