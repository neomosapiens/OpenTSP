"""Generate the human- and tool-readable ISA reference from isa-db (single source; the
catalogue itself is checked against the Sail model by tools/isa_db_check.sh):

  opentsp-arch-spec/docs/isa.md       instruction reference (per slice)
  opentsp-arch-spec/docs/encoding.md  encoding map (bit layouts, opcode allocation)
  opentsp-arch-spec/isa-db/generated/encoding.json  machine-readable tables for the ISS
                                                    and assembler

usage: gen_isa_doc.py [--check]   (--check: fail if the outputs are out of date)
"""
import argparse, glob, json, os, re, sys
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "..")
REPO = os.path.join(SPEC, "..")
DOCS = os.path.join(SPEC, "docs")
ORDER = ["CU", "MEM", "VXM", "MXM", "SXM", "C2C"]
TYPES = ["i8", "f16", "i32", "f32", "u8", "i16", "u16", "u32", "b8", "b16", "b32", "e4m3", "e5m2"]
# The element type codes: the base set by position, then the profile extension types (the type-extension bit 4 of the code).
TYPE_CODES = {**{t: i for i, t in enumerate(TYPES)}, "bf16": 16}
TYPE_NAME = {c: t for t, c in TYPE_CODES.items()}
SLICE_TAG = {"CU": 0, "MEM": 1, "VXM": 2, "MXM": 3, "SXM": 4, "C2C": 5}
# The control channel accepts these instructions (model/postlude/tick.sail `control`); every
# other decoded instruction there is OTS-E-QUE-002.
CONTROL_CHANNEL = ("NOP", "Sync", "Notify", "Config")


def entries():
    es = [yaml.safe_load(open(f)) for f in glob.glob(os.path.join(SPEC, "isa-db", "instructions", "*.yaml"))]
    return sorted(es, key=lambda e: (ORDER.index(e["slice"]), int(opcode(e), 2), e["name"]))


def opcode(e):
    m = e["encoding"]["match"]
    w = e["encoding"]["width"]
    return m[w - 28:w - 22] if w == 32 else m[w - 60:w - 54]


def var_desc(v):
    loc = v["location"] + (f" + {v['hi_location']}" if "hi_location" in v else "") + (f" + {v['top_location']}" if "top_location" in v else "")
    extra = ""
    if "codes" in v:
        extra = ", types " + " ".join(TYPE_NAME[c] for c in v["codes"])
        if "extension_codes" in v:
            extra += " (" + ", ".join(f"{TYPE_NAME[c]} only with the extension `{e}`" for e, cs in v["extension_codes"].items() for c in cs) + ")"
    elif "values" in v:
        extra = ", values " + " ".join(map(str, v["values"]))
        if "extension_codes" in v:
            extra += " (" + ", ".join(f"{c} only with the extension `{e}`" for e, cs in v["extension_codes"].items() for c in cs) + ")"
    if "not_values" in v:
        extra += ", not " + " ".join(map(str, v["not_values"]))
    if "min" in v or "max" in v:
        extra += f", range {v.get('min', 0)}..{v.get('max', '')}"
    if "max_expr" in v:
        extra += f", at most {v['max_expr']}"
    return f"`{v['name']}` {loc} ({v['kind']}{extra})"


def isa_md(es):
    out = ["# TSP ISA reference (generated, spec version 0.1)", "",
           "Generated by `opentsp-arch-spec/tools/gen_isa_doc.py` from `opentsp-arch-spec/isa-db/instructions/*.yaml`. "
           "Do not edit by hand. The Sail model (`opentsp-arch-spec/model/`) is normative, and the catalogue is checked "
           "against it field by field (`tools/isa_db_check.sh`). Sources for each instruction are in "
           "`isa-db/provenance.yaml`; assembly syntax is in `assembly.md`; encodings are in `encoding.md`. "
           "Timing is the entry's timing class: its (d_func, d_skew) row in `config/<profile>.json` unless "
           "`timing.overrides` gives the entry its own row, or a row `<entry>.<type>` for one element type (microarchitecture.md sec. 1).", "",
           f"{len(es)} encodings.", ""]
    for s in ORDER:
        group = [e for e in es if e["slice"] == s]
        out += [f"## {s} ({len(group)})", "", "| Instruction | Assembly | Units | Timing | Operation |", "|---|---|---|---|---|"]
        for e in group:
            out.append(f"| {e['long_name']} (`{e['name']}`) | `{e['assembly']}` | {', '.join(e['units'])} | {e['timing']} | {e['operation']} |")
        out.append("")
    return "\n".join(out)


def operand_bits(enc):
    def n(loc):
        a, _, b = loc.partition("-")
        return int(a) - int(b or a) + 1
    return sum(n(v["location"]) + (n(v["hi_location"]) if "hi_location" in v else 0) + (n(v["top_location"]) if "top_location" in v else 0)
               for v in enc["variables"])


