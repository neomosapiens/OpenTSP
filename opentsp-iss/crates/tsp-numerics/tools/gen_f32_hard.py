#!/usr/bin/env python3
"""reference/f32_hard.txt: f32 inputs on which the fast path of the transcendentals declines (the double
value is within 2^-40 of a rounding boundary), with the correctly rounded results.

  gen_f32_hard.py --screen-work DIR [--per-op N]

DIR is the --work directory of opentsp-arch-spec/tools/check_transcendental_f32.sh (validation
f32 screening: it sweeps all 2^32 inputs of the four functions, lists the hard ones in hard.txt and
rechecks them with mpmath, results in jobs_eval.txt; the Sail model agrees on all of them). The
file holds N evenly spaced inputs per function among the hard ones that make the Rust fast path
decline, plus the closest one of each (f32 screening report).
"""
import argparse
import math
import os
import struct

CLOSEST = {21: 0x3AC37DE2, 22: 0xC16912CD, 23: 0x013A18E3, 24: 0x65D890D3}


def declines(op, bits):
    """Does the Rust fast path decline this input? (Python's math module calls the same libm as
    Rust's f64 methods; the grid test is tsp_numerics::transcendental::round_on_grid.)"""
    x = struct.unpack("<f", struct.pack("<I", bits))[0]
    try:
        v = {21: math.tanh, 22: math.exp, 23: lambda t: 1.0 / math.sqrt(t), 24: math.log}[op](x)
    except (ValueError, OverflowError, ZeroDivisionError):
        return False
    av = abs(v)
    if av == 0.0 or math.isinf(av):
        return True
    _, e = math.frexp(av)
    ee = max(e - 1, -126)
    qe = ee - 23
    s = math.ldexp(av, -qe)
    fl = math.floor(s)
    dist = abs((s - fl) - 0.5)
    return not (dist > s * 2.0 ** -40)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--screen-work", required=True)
    ap.add_argument("--per-op", type=int, default=160)
    a = ap.parse_args()
    expected = {}
    for line in open(os.path.join(a.screen_work, "jobs_eval.txt")):
        f = line.split()
        if len(f) == 4 and f[0] == "E":
            expected[(int(f[1]), int(f[2], 16))] = int(f[3], 16)
    hard = {21: [], 22: [], 23: [], 24: []}
    for line in open(os.path.join(a.screen_work, "hard.txt")):
        f = line.split()
        hard[int(f[0])].append(int(f[1], 16))
    out = ["# f32 inputs on which the fast path declines (within 2^-40 of a rounding boundary); results are mpmath's, checked",
           "# against the Sail model by the exhaustive f32 check (the f32 screening check). Format: tools/numerics_jobs.py.",
           "# Generated by tools/gen_f32_hard.py from a check_transcendental_f32.sh work directory."]
    for op in (21, 22, 23, 24):
        xs = [x for x in hard[op] if declines(op, x)]
        print("op %d: %d of %d hard inputs make the fast path decline" % (op, len(xs), len(hard[op])))
        step = max(1, len(xs) // a.per_op)
        pick = xs[::step][: a.per_op]
        if CLOSEST[op] not in pick:
            pick.append(CLOSEST[op])
        for x in pick:
            out.append("tr %d 32 %x = %08x" % (op, x, expected[(op, x)]))
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "reference", "f32_hard.txt"), "w").write("\n".join(out) + "\n")
    print(len(out) - 3, "inputs")


if __name__ == "__main__":
    main()
