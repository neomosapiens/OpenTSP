#!/usr/bin/env python3
"""Generate the checked-in reference output of the tsp-numerics tests from the mpmath oracle
(opentsp-arch-spec/test/oracle/numerics.py). Not needed to run the tests, only to regenerate.

  gen_reference.py sample [--sail OUT.txt]   reference/sample.txt: the jobs of
                                             numerics_jobs.sample_jobs() with the oracle's results;
                                             --sail checks them against a tools/sail_dump.sh output
                                             of the same jobs (any difference fails)
  gen_reference.py hashes [--procs N]        reference/oracle_hashes.txt: SHA-256 of the oracle's
                                             result stream for every set of numerics_jobs.set_specs()
  gen_reference.py jobs OUT.txt              write the sample's job list (input of sail_dump.sh)
  gen_reference.py all [--sail OUT.txt]

The oracle computes every transcendental correctly rounded with mpmath at increasing precision,
and every other kernel exactly with fractions: it is the independent half of the checks; the Sail
model (sail_dump.sh) is the normative half.
"""
import argparse
import hashlib
import multiprocessing as mp
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numerics_jobs as J  # noqa: E402

REF = os.path.join(HERE, "..", "reference")


def spec_line(name, kind, args, inp):
    return "%s %s %s" % (name, kind, ",".join(str(a) for a in args)) + " " + " ".join(str(i) for i in inp)


def run_spec(spec):
    name, kind, args, inp = spec
    res = J.spec_results(kind, args, inp)
    h = hashlib.sha256()
    for v, w in res:
        h.update((v & ((1 << (8 * w)) - 1)).to_bytes(w, "little"))
    return name, len(res), h.hexdigest()


def cmd_hashes(procs):
    specs = J.set_specs()
    # the big ones first
    order = sorted(range(len(specs)), key=lambda i: -{"tr": 9, "cvt": 5, "bin": 4, "cmp": 3}.get(specs[i][1], 1))
    with mp.Pool(procs) as pool:
        done = pool.imap_unordered(run_spec, [specs[i] for i in order])
        results = {}
        for n, (name, count, digest) in enumerate(done):
            results[name] = (count, digest)
            print("\r%d/%d %s" % (n + 1, len(specs), name), end="", file=sys.stderr, flush=True)
    print(file=sys.stderr)
    with open(os.path.join(REF, "oracle_hashes.txt"), "w") as f:
        f.write("# tsp-numerics: SHA-256 of the mpmath oracle's result stream per input set.\n")
        f.write("# Generated by tools/gen_reference.py hashes (opentsp-arch-spec/test/oracle/numerics.py);\n")
        f.write("# input sets and stream format: tools/numerics_jobs.py (module docstring).\n")
        f.write("# H <name> <count> <sha256> <kind> <args> <inputs...>\n")
        for name, kind, args, inp in specs:
            count, digest = results[name]
            f.write("H %s %d %s %s %s %s\n" % (name, count, digest, kind, ",".join(str(a) for a in args),
                                               " ".join(str(i) for i in inp)))
    print("wrote %d sets" % len(specs))


def cmd_sample(sail):
    jobs = J.sample_jobs()
    lines = ["%s = %s" % (j, J.fmt_result(J.oracle_job(j))) for j in jobs]
    if sail:
        theirs = [l.rstrip("\n") for l in open(sail)]
        bad = [(a, b) for a, b in zip(lines, theirs) if a != b]
        if len(theirs) != len(lines) or bad:
            for a, b in bad[:20]:
                print("oracle: %s\nsail:   %s" % (a, b), file=sys.stderr)
            sys.exit("sample: %d differences (%d vs %d lines)" % (len(bad), len(lines), len(theirs)))
        print("sample: the Sail model and the oracle agree on %d jobs" % len(lines))
    with open(os.path.join(REF, "sample.txt"), "w") as f:
        f.write("# tsp-numerics reference sample: <job> = <result>. Format: tools/numerics_jobs.py.\n")
        f.write("# Results of the mpmath oracle, equal to the Sail model's (tools/gen_reference.py sample --sail).\n")
        f.write("\n".join(lines) + "\n")
    print("wrote %d jobs" % len(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["sample", "hashes", "jobs", "all"])
    ap.add_argument("out", nargs="?")
    ap.add_argument("--sail")
    ap.add_argument("--procs", type=int, default=os.cpu_count())
    a = ap.parse_args()
    os.makedirs(REF, exist_ok=True)
    if a.cmd == "jobs":
        with open(a.out, "w") as f:
            f.write("\n".join(J.sample_jobs()) + "\n")
        return
    if a.cmd in ("sample", "all"):
        cmd_sample(a.sail)
    if a.cmd in ("hashes", "all"):
        cmd_hashes(a.procs)


if __name__ == "__main__":
    main()
