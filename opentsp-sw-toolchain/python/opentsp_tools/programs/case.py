"""Program construction state shared by model builders and test scenarios."""
import numpy as np
from .kernels import Builder
from . import data
from opentsp_tools import emit

class Kit:
    """A Builder plus the case's weights, dumps and expected words."""

    def __init__(self, p, name, doc, seed, module="basic", tags=("sim",), preload=None, source="hand"):
        self.p, self.name, self.seed, self.module, self.source = p, name, seed, module, source
        self.tags, self.preload = tags, preload or {}
        self.rng = np.random.default_rng(seed)
        self.b = Builder(p, f"{name}: {doc}; profile {p.name}, seed {seed}.\n"
                            "Generated by tests/programs/gen/build.py; do not edit.")
        self.weights, self.words, self.dump, self.diags = {}, {}, [], []
        self.last = 0

    def lead(self, op, quads=4):
        """The first dispatch cycle of the VXM operation `op` (with its type: `add.i8`) at which operands read at cycle 0 or later from
        west quads 0..quads-1 can arrive (the sec. 1 equation, from the profile)."""
        L = self.p.layout
        return self.p.timing("read")[0] + L["vxm_gap"] - (L["mem_up_gap_base"] - quads + 1) - self.p.timing(op)[1]

    def place(self, nm, arr, quad, addr, hemi="W"):
        """Bind arr's byte planes as externs on the slices of a quad; returns (slices, extern names)."""
        return self.place_planes(nm, data.to_planes(arr), quad, addr, hemi)

    def place_planes(self, nm, planes, quad, addr, hemi="W"):
        base = (0 if hemi == "W" else 44) + 4 * quad
        slices = list(range(base, base + len(planes)))
        names = []
        for k, (s, pl) in enumerate(zip(slices, planes)):
            n = f"{nm}p{k}"
            self.b.prog.extern(n, s, addr, 1)
            self.weights[n] = ("raw" if len(planes) > 1 else "i8", pl)
            names.append(n)
        return slices, names

    def feed(self, placed, addr, row, stream, t, consumer, queue=88):
        """Read the planes `place` bound so that they meet `consumer` dispatched at t on `queue`."""
        slices, names = placed
        return self.b.read_for(t, consumer, queue, slices, [addr] * len(slices), row, stream, addr_text=names)

    def load(self, nm, arr, quad, addr, row, stream, t, consumer, queue=88, hemi="W"):
        """Place arr's planes on the slices of a quad as externs and read them to meet `consumer` at t."""
        return self.feed(self.place(nm, arr, quad, addr, hemi), addr, row, stream, t, consumer, queue)

    def store(self, v, quad, addr, expect, hemi="E"):
        planes = data.to_planes(expect)
        base = (0 if hemi == "W" else 44) + 4 * quad
        slices = list(range(base, base + v.width))
        t = self.b.write(v, slices, [addr] * v.width)
        for s, pl in zip(slices, planes):
            self.dump.append((s, addr))
            self.words[(s, addr)] = pl
        self.last = max(self.last, t)

    def extern_word(self, nm, s, addr, word):
        self.b.prog.extern(nm, s, addr, 1)
        self.weights[nm] = ("i8", word)

    def expect(self, s, addr, word):
        self.dump.append((s, addr))
        self.words[(s, addr)] = word

    def done(self, fn):
        text = self.b.finish()
        return text, emit.case(self.name, self.p, weights=self.weights, preload=self.preload, dump=self.dump,
                               words=self.words, diagnostics=self.diags, tags=self.tags,
                               golden={"source": self.source, "generator": f"gen/{self.module}.py:{fn}",
                                       "seed": self.seed},
                               cycles=self.last + 16)
