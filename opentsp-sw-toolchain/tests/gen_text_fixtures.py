#!/usr/bin/env python3
"""Golden cases for the text layer (`ots-format`): lower, raise_images and q_lines of
`opentsp-arch-spec/tools/tsp_as.py` on seeded random programs, written to
crates/ots-format/tests/data/lower.txt. The Rust tests read that file and require the same
answers. Regenerate with:  python3 opentsp-sw-toolchain/tests/gen_text_fixtures.py [--check]

Case format (each case starts with a line C):
  E <cycle> <queue hex> <word hex>     one entry of the cycle view, in order
  Q <queue hex> <unit hex> ...         one q_lines line of the lowering (at most 64 units)
  R <cycle> <queue hex> <word hex> <n> raise_images(lower(entries)) in order
"""
import os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "opentsp-arch-spec", "tools"))
import tsp_as as A

OUT = os.path.join(HERE, "..", "crates", "ots-format", "tests", "data", "lower.txt")


def word(rnd, nop_ok=True):
    k = rnd.randrange(10)
    if k == 0 and nop_ok:
        return rnd.randrange(1, 0x10000)                       # NOP n
    if k == 1:
        return rnd.getrandbits(60) | (rnd.choice((1, 2, 4)) << 60)    # wide
    if k == 2:
        return rnd.getrandbits(64)                             # anything, often undecodable
    if k == 3:
        return rnd.choice((0x6FFFFFFF, 0x7FFFFFFF, 0x80000000, 0x1_0000_0000))
    return (rnd.choice((0, 3, 5)) << 28) | rnd.getrandbits(28)  # narrow


def cases():
    rnd = random.Random(20261113)
    out = [
        [],                                                    # empty program
        [(0, 0, 0x00400000)],                                  # sync at cycle 0
        [(0, 0, 5)],                                           # a lone NOP: no text
        [(3, 0, 5), (3, 0, 0x00400000)],                       # a NOP with another entry stays in the parcel
        [(70000, 1, 0x00400000)],                              # a gap above 65535: two NOP units
        [(65535, 1, 0x00400000), (65535 + 65536 + 1, 1, 0x00800000)],
        [(0, 0xFFFF, 0x00400000), (2, 3, 0x00800000), (0, 3, 0x00400000)],   # control channel last, sorted
        [(1, 7, 0x1000000000000000), (1, 7, 0x00400000)],      # a wide word then a narrow one in a parcel
        [(0, 9, 0x6FFFFFFF0)],                                 # a word that fits no layout
    ]
    for _ in range(250):
        n = rnd.randrange(1, 14)
        ents = []
        cyc = 0
        for _ in range(n):
            cyc += rnd.choice((0, 0, 1, 1, 2, 5, 70000, 65535, 65536, 131071)) if rnd.random() < 0.8 else 0
            q = rnd.choice((0, 1, 2, 43, 88, 143, 0xFFFF))
            ents.append((cyc, q, word(rnd)))
        rnd.shuffle(ents) if rnd.random() < 0.3 else None
        out.append(ents)
    return out


def render():
    lines = ["# generated by opentsp-sw-toolchain/tests/gen_text_fixtures.py; do not edit"]
    for ents in cases():
        lines.append("C")
        lines += [f"E {c} {q:x} {w:x}" for c, q, w in ents]
        imgs = A.lower(ents)
        lines += A.q_lines(imgs)
        lines += [f"R {c} {q:x} {w:x} {n}" for c, q, w, n in A.raise_images(imgs)]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT}")
