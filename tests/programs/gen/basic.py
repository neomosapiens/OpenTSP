"""Category A of the design's sec. 2.2: MEM -> VXM -> MEM pipelines (the families
vec_add, mem_read_write, multi_slice_pipeline, mem_cross_quad, f16_add_chain, vxm_add_* and
vxm_chain families). Every cycle follows from the profile through the toolchain; expectations are hand rules stated here."""
import random

import numpy as np

from opentsp_tools.programs.kernels import Builder
from opentsp_tools.programs import data
from opentsp_tools import emit
from opentsp_tools import stations

# : every category A-G program on ref and mini, and on the alternative-timing profile ref_slow,
# which guards the rule that every latency comes from the profile.
PROFILES = ["ref", "mini", "test/ref_slow"]
# The basic programs also run on a profile of 8 and one of 32 superlanes (512 lanes).
GEOMETRY_PROFILES = PROFILES + ["test/sl8", "test/sl32"]


def rand_word(rng, p):
    return bytes(rng.randrange(256) for _ in range(p.vlanes))


def vec_add(p, seed=1, src_quad=1, dst_slice=44, t0=0):
    """z = x + y on i8 lanes (wrapping): x and y are externs on two west slices of quad `src_quad`, read onto row E
    in one cycle, added on VXM[0], written onto row E to the east slice `dst_slice` (the assembly.md sec. 3 data
    path, parameterised)."""
    rng = random.Random(seed)
    sx, sy = 4 * src_quad, 4 * src_quad + 1
    ax, ay, az = 0x10, 0x20, 0x9
    x, y = rand_word(rng, p), rand_word(rng, p)
    z = bytes((a + b) & 0xFF for a, b in zip(x, y))
    b = Builder(p, f"basic/vec_add: z = x + y (i8, wrapping); profile {p.name}, seed {seed}.\n"
                   "Generated by tests/programs/gen/build.py; do not edit.")
    b.prog.extern("x", sx, ax, 1)
    b.prog.extern("y", sy, ay, 1)
    vx = b.read(t0, [sx], [ax], "E", 0, addr_text=["x"])
    vy = b.read(t0, [sy], [ay], "E", 4, addr_text=["y+0x0"])
    vz = b.vxm(0, "add.i8", "E", 8, [vx, vy])
    t_w = b.write(vz, [dst_slice], [az])
    text = b.finish()
    case = emit.case("basic/vec_add", p, weights={"x": ("i8", x), "y": ("i8", y)},
                     dump=[(dst_slice, az)], words={(dst_slice, az): z},
                     golden={"source": "hand", "generator": "gen/basic.py:vec_add", "seed": seed},
                     cycles=t_w + 16, tags=("sim", "e2e"))
    return text, case


from opentsp_tools.programs.case import Kit


def wide_types(p, seed=1):
    """add, sub and mul on i16, i32 (wrapping) and f32 (IEEE, round to nearest even): x on west quad 1, y on west
    quad 2, read onto row E; the three operations of a type run on VXM[0..2] in one cycle and their results go to
    east quads 0, 1, 2 (one plane per slice). The 32-bit types use four aligned byte-plane streams."""
    k = Kit(p, "basic/wide_types", "add, sub, mul on i16, i32, f32", seed)
    for j, t in enumerate(["i16", "i32", "f32"]):
        n = p.vlanes
        x = data.rand_float(k.rng, t, n) if t[0] == "f" else data.rand_int(k.rng, t, n)
        y = data.rand_float(k.rng, t, n) if t[0] == "f" else data.rand_int(k.rng, t, n)
        tv = k.lead(f"add.{t}") + 12 * j
        vx = k.load(f"x{t}", x, 1, 0x10 + j, "E", 0, tv, f"add.{t}")
        vy = k.load(f"y{t}", y, 2, 0x10 + j, "E", 4, tv, f"add.{t}")
        with np.errstate(all="ignore"):
            res = {"add": x + y, "sub": x - y, "mul": x * y}
        for i, op in enumerate(["add", "sub", "mul"]):
            v = k.b.vxm(i, f"{op}.{t}", "E", 8 + 4 * i, [vx, vy], cycle=tv)
            k.store(v, i, 0x20 + j, res[op])
    return k.done("wide_types")


def vxm_chain(p, seed=1):
    """r = w + ((x * y) - z) on i32 with explicit ALU chaining: VXM[0] multiplies, VXM[1] subtracts
    with its lhs chained, VXM[2] adds with its rhs chained (t2 = t1 + d_func - d_skew + 1). z and w arrive on their
    diagonals at the chained operations' read cycles. The intermediate x * y still flows on its stream, so an east
    slice downstream writes it too."""
    k = Kit(p, "basic/vxm_chain", "r = w + ((x * y) - z), i32, chained ALUs", seed)
    n = p.vlanes
    x, y, z, w = (data.rand_int(k.rng, "i32", n) for _ in range(4))
    t0 = k.lead("mul.i32")
    t1 = t0 + p.timing("mul.i32")[0] - p.timing("sub.i32")[1] + 1       # the sub reads the product at the station, one cycle after its commit
    t2 = t1 + p.timing("sub.i32")[0] - p.timing("add.i32")[1] + 1
    vx = k.load("x", x, 1, 0x10, "E", 0, t0, "mul.i32")
    vy = k.load("y", y, 2, 0x10, "E", 4, t0, "mul.i32")
    vz = k.load("z", z, 1, 0x11, "E", 12, t1, "sub.i32", 89)
    vw = k.load("w", w, 2, 0x11, "E", 16, t2, "add.i32", 90)
    with np.errstate(all="ignore"):
        m = x * y
        s = m - z
        r = w + s
    vm = k.b.vxm(0, "mul.i32", "E", 8, [vx, vy])
    vs = k.b.vxm(1, "sub.i32", "E", 20, [vm, vz], chain=(0,))
    vr = k.b.vxm(2, "add.i32", "E", 24, [vw, vs], chain=(1,))
    k.store(vr, 0, 0x20, r)
    k.store(vm, 1, 0x20, m)
    return k.done("vxm_chain")


def f16_chain(p, seed=1):
    """s = ((x + y) + z) + w in f16, each step rounded to nearest even in f16 (no wider accumulator), the partial sums
    passed from ALU to ALU by chained lhs operands; every operand is a stream pair from two slices of one quad."""
    k = Kit(p, "basic/f16_chain", "s = ((x + y) + z) + w, f16", seed)
    n = p.vlanes
    x, y, z, w = (data.rand_float(k.rng, "f16", n, -6, 6) for _ in range(4))
    d_func, d_skew = p.timing("add.f16")
    t0 = k.lead("add.f16")
    t1 = t0 + d_func - d_skew + 1
    t2 = t1 + d_func - d_skew + 1
    vx = k.load("x", x, 1, 0x10, "E", 0, t0, "add.f16")
    vy = k.load("y", y, 2, 0x10, "E", 2, t0, "add.f16")
    vz = k.load("z", z, 1, 0x11, "E", 4, t1, "add.f16", 89)
    vw = k.load("w", w, 2, 0x11, "E", 6, t2, "add.f16", 90)
    s1 = k.b.vxm(0, "add.f16", "E", 8, [vx, vy])
    s2 = k.b.vxm(1, "add.f16", "E", 10, [s1, vz], chain=(0,))
    s3 = k.b.vxm(2, "add.f16", "E", 12, [s2, vw], chain=(0,))
    k.store(s3, 0, 0x20, ((x + y) + z) + w)
    return k.done("f16_chain")


def vxm_typed(p, seed=1):
    """max on i8 and on f32, then an add whose lhs is the chained max: a profile may time `max.i8` apart from `max.f32` (a typed row
    of `timing.overrides`, test/ref_hw: 3 and 7 against the class row 5), and the chained add is dispatched from the commit of the
    typed row. On a profile without typed rows both maxima take the class row. The program is scheduled with the typed row of each
    operation and then run: a schedule that used the class row would read the max result at the wrong cycle."""
    k = Kit(p, "basic/vxm_typed", "max.i8 and max.f32, each followed by a chained add", seed)
    n = p.vlanes
    for j, t in enumerate(["i8", "f32"]):
        x = data.rand_float(k.rng, t, n) if t[0] == "f" else data.rand_int(k.rng, t, n)
        y = data.rand_float(k.rng, t, n) if t[0] == "f" else data.rand_int(k.rng, t, n)
        z = data.rand_float(k.rng, t, n) if t[0] == "f" else data.rand_int(k.rng, t, n)
        tv = k.lead(f"max.{t}") + 16 * j
        t1 = tv + p.timing("max", t)[0] - p.timing("add", t)[1] + 1
        vx = k.load(f"x{t}", x, 1, 0x10 + j, "E", 0, tv, f"max.{t}")
        vy = k.load(f"y{t}", y, 2, 0x10 + j, "E", 4, tv, f"max.{t}")
        vz = k.load(f"z{t}", z, 1, 0x14 + j, "E", 12, t1, f"add.{t}", 89)
        with np.errstate(all="ignore"):
            m = np.maximum(x, y)
            r = z + m
        vm = k.b.vxm(0, f"max.{t}", "E", 8, [vx, vy], cycle=tv)
        vr = k.b.vxm(1, f"add.{t}", "E", 20, [vm, vz], chain=(0,))
        k.store(vm, 0, 0x20 + j, m)
        k.store(vr, 1, 0x20 + j, r)
    return k.done("vxm_typed")


def route_pairs(p, every):
    """(row, src hemisphere, src quad, dst hemisphere, dst quad) of each MEM -> MEM route that a row allows: on row E
    west -> east (all pairs), west -> west towards lower quads, east -> east towards higher quads; row W mirrored.
    `every`: every pair; else each quad once as source and once as destination per kind, plus the farthest hop."""
    nq = (p.slices_per_hemisphere + 3) // 4
    out = []
    for row, near, far in (("E", "W", "E"), ("W", "E", "W")):
        cross = [(a, b) for a in range(nq) for b in range(nq)]
        down = [(a, b) for a in range(nq) for b in range(nq) if b < a]     # near hemisphere, towards lower quads
        up = [(a, b) for a in range(nq) for b in range(nq) if b > a]       # far hemisphere, towards higher quads
        if not every:
            cross = [(a, (a + (0 if row == "E" else nq // 2)) % nq) for a in range(nq)]
            down = [(a, a - 1) for a in range(1, nq)] + ([(nq - 1, 0)] if nq > 2 else [])
            up = [(a, a + 1) for a in range(nq - 1)] + ([(0, nq - 1)] if nq > 2 else [])
        out += [(row, near, a, far, b) for a, b in cross]
        out += [(row, near, a, near, b) for a, b in down]
        out += [(row, far, a, far, b) for a, b in up]
    return out


def mem_route(p, seed=1, every=None):
    """Copy one word per route of route_pairs: a Read on the source slice onto the route's row, a Write on the
    destination slice at the cycle the value reaches its gap. Sources are in bank 0, destinations in bank 1, so a
    slice may read and write in one cycle. Reads are placed greedily (earliest cycle, lowest free stream)."""
    every = p.vlanes <= 16 if every is None else every
    k = Kit(p, "basic/mem_route", "MEM -> MEM on rows E and W over the quad pairs each row allows", seed)
    rng = random.Random(seed)
    spq = 4
    nxt_src, nxt_dst = {}, {}
    busy = set()          # (slice, cycle, path)
    occ = {}              # (row, stream, diagonal) -> [(g_lo, g_hi)]
    d_func, _ = p.timing("read")
    for i, (row, hs, qs, hd, qd) in enumerate(route_pairs(p, every)):
        base_s, base_d = (0 if hs == "W" else 44) + 4 * qs, (0 if hd == "W" else 44) + 4 * qd
        s_src = base_s + i % min(spq, p.slices_per_hemisphere - 4 * qs)
        s_dst = base_d + (i // 2) % min(spq, p.slices_per_hemisphere - 4 * qd)
        g_w = stations.need_gap(p, s_src, row, "write")
        g_r = stations.need_gap(p, s_dst, row, "read")
        a_src = nxt_src.get(s_src, 0)
        a_dst = nxt_dst.get(s_dst, 1 << p.bank_bit)
        nxt_src[s_src], nxt_dst[s_dst] = a_src + 1, a_dst + 1
        t = 0
        while True:
            t_w = t + d_func + (g_r - g_w)
            if (s_src, t, "R") not in busy and (s_dst, t_w, "W") not in busy:
                diag = t + d_func - g_w
                free = [s for s in range(p.streams)
                        if all(hi < g_w or lo > g_r for lo, hi in occ.get((row, s, diag), []))]
                if free:
                    break
            t += 1
        st = free[0]
        occ.setdefault((row, st, diag), []).append((g_w, g_r))
        busy |= {(s_src, t, "R"), (s_dst, t_w, "W")}
        word = bytes(rng.randrange(256) for _ in range(p.vlanes))
        n = f"s{i}"
        k.b.prog.extern(n, s_src, a_src, 1)
        k.weights[n] = ("i8", word)
        v = k.b.read(t, [s_src], [a_src], row, st, addr_text=[n])
        k.last = max(k.last, k.b.write(v, [s_dst], [a_dst]))
        k.dump.append((s_dst, a_dst))
        k.words[(s_dst, a_dst)] = word
    return k.done("mem_route")


